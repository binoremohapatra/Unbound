"""gen_constants.py - emit firmware + host constants from protocol/constants.json.

  python tools/gen_constants.py          # (re)generate both outputs
  python tools/gen_constants.py --check  # exit 1 if committed outputs are stale

Outputs:
  firmware/omniband_v2_firmware/constants_gen.h   (C++17, no Arduino includes)
  host/omniband/constants_gen.py                  (Python dict + helpers)

Naming: dotted path segments -> CamelCase, prefix k for C++.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "protocol" / "constants.json"
OUT_H = ROOT / "firmware" / "omniband_v2_firmware" / "constants_gen.h"
OUT_PY = ROOT / "host" / "omniband" / "constants_gen.py"

RESERVED = {"version", "meta"}


def _camel(seg: str) -> str:
    return "".join(w.capitalize() for w in seg.split("_") if w)


def _c_name(parts: list[str]) -> str:
    return "k" + "".join(_camel(p) for p in parts)


def _cpp_scalar(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    raise TypeError(f"cannot emit {v!r}")


def _flatten(obj, path=()):
    """Yield (path_tuple, leaf) for scalars and homogeneous lists."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k.startswith("_"):
                continue
            yield from _flatten(v, path + (k,))
    elif isinstance(obj, list):
        if all(isinstance(x, str) for x in obj):
            yield path, obj
        elif all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in obj):
            yield path, obj
        elif not obj:
            yield path, obj
        else:
            for i, v in enumerate(obj):
                yield from _flatten(v, path + (str(i),))
    else:
        yield path, obj


def gen_header(data: dict) -> str:
    lines = [
        "// constants_gen.h - GENERATED by tools/gen_constants.py from protocol/constants.json",
        "// DO NOT EDIT. Regenerate with: python tools/gen_constants.py",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace omniband {",
        "namespace constants {",
        "",
    ]
    modes = data.get("modes", [])
    mode_keys = {k for m in modes for k in m}
    scalar_paths = []
    for path, leaf in _flatten(data):
        if path and path[0] in ("meta", "modes"):
            continue
        if path[-1].isdigit():
            continue  # inside a list-of-dicts we don't flatten
        scalar_paths.append((path, leaf))

    for path, leaf in scalar_paths:
        name = _c_name(list(path))
        if isinstance(leaf, list):
            if all(isinstance(x, str) for x in leaf):
                lines.append(f'inline constexpr const char* {name}[] = {{'
                             + ", ".join(json.dumps(x) for x in leaf) + "};")
            else:
                t = "double" if any(isinstance(x, float) for x in leaf) else "int32_t"
                lines.append(
                    f"inline constexpr std::array<{t}, {len(leaf)}> {name} = {{"
                    + ", ".join(_cpp_scalar(x) for x in leaf) + "};")
        else:
            t = ("const char*" if isinstance(leaf, str) else
                 "bool" if isinstance(leaf, bool) else
                 "double" if isinstance(leaf, float) else "int32_t")
            lines.append(f"inline constexpr {t} {name} = {_cpp_scalar(leaf)};")
    lines.append("")

    # Mode policy table -> struct array
    bool_fields = ["fast_events", "sos", "estop", "mode_change_pc_only", "night_mode"]
    int_fields = ["id", "sos_confirm_ms", "long_hold_ms", "xt_lookahead_ms",
                  "host_silence_ms"]
    str_fields = ["name", "tag"]   # "short" is a C++ keyword - JSON uses "tag"
    fields = str_fields + bool_fields + int_fields
    lines.append("struct ModePolicy {")
    for f in fields:
        if f in str_fields:
            lines.append(f"  const char* {f};")
        elif f in bool_fields:
            lines.append(f"  bool {f};")
        else:
            lines.append(f"  int32_t {f};")
    lines.append("};")
    lines.append(f"inline constexpr ModePolicy kModes[{len(modes)}] = {{")
    for m in modes:
        vals = []
        for f in fields:
            v = m.get(f)
            if f in str_fields:
                vals.append(json.dumps(v if v is not None else ""))
            elif f in bool_fields:
                vals.append("true" if v else "false")
            else:
                vals.append(str(int(v or 0)))
        lines.append("  {" + ", ".join(vals) + "},")
    lines.append("};")
    lines.append(f"inline constexpr int32_t kModeCount = {len(modes)};")
    lines.append("")
    lines.append("}  // namespace constants")
    lines.append("}  // namespace omniband")
    lines.append("")
    return "\n".join(lines)


def gen_python(data: dict) -> str:
    import pprint
    body = pprint.pformat(data, width=100, sort_dicts=False)
    return (
        '"""constants_gen.py - GENERATED by tools/gen_constants.py. DO NOT EDIT."""\n'
        "from __future__ import annotations\n\n"
        "CONSTANTS = " + body + "\n\n"
        "# ---- derived helpers (single source stays constants.json) ----\n"
        "MODES = {m[\"id\"]: m for m in CONSTANTS[\"modes\"]}\n"
        "MODE_BY_TAG = {m[\"tag\"]: m[\"id\"] for m in CONSTANTS[\"modes\"]}\n"
        "MODE_COUNT = len(CONSTANTS[\"modes\"])\n"
        "GESTURES = frozenset(CONSTANTS[\"gestures\"])\n"
        "RAW_EVENT_TYPES = frozenset(CONSTANTS[\"raw_event_types\"])\n"
        "TELE_FLAGS = dict(CONSTANTS[\"tele_flags\"])\n"
        "HOST_COMMANDS = frozenset(CONSTANTS[\"host_commands\"])\n"
        "CAPS = frozenset(CONSTANTS[\"caps\"])\n\n"
        "def mode_of(mode_id: int) -> dict:\n"
        "    return MODES.get(int(mode_id), MODES[0])\n"
        "\n"
        "def flags_to_names(flags: int) -> list[str]:\n"
        "    return [n for n, b in TELE_FLAGS.items() if flags & b]\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = json.loads(SRC.read_text(encoding="utf-8"))
    header = gen_header(data)
    py = gen_python(data)
    pairs = [(OUT_H, header), (OUT_PY, py)]
    stale = []
    for path, content in pairs:
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if args.check:
        if stale:
            print("STALE generated files: " + ", ".join(stale))
            print("run: python tools/gen_constants.py")
            return 1
        print("generated files are up to date")
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
